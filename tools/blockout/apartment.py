def cameras():
    """Имя камеры = имя будущего фона.

    Фокусное 28 мм, а не 35 из документа: в комнате 3,4 м от стены до стены 35 мм
    видит полторы метра и кадр превращается в кусок стола. 24 мм — для санузла
    и коридора, где иначе не видно ничего.
    """
    c = {}
    EYE = 1.5
    SH = -0.11   # кадр опущен объективом: мебель стоит на полу, а не под обрезом
    # Комната героя: три ракурса одной комнаты — ровно то, чего не удержит генератор
    # Фронтально, а не из угла по диагонали: при диагонали ближняя боковая стена занимает
    # треть кадра, и комната 3,4 м читается как коридор в полтора метра — генератор
    # честно рисует то, что видит
    # Кадр со снятой четвёртой стеной: камера стоит ЗА стеной комнаты, сама стена
    # при рендере скрывается (hide в main). Изнутри комнату 3,4x3,1 снять нельзя —
    # камера упирается в стену, боковые стены встают по краям во всю высоту,
    # и генератор читает кадр как коридор шириной полтора метра. Снаружи видно
    # пол, потолок и все три стены, то есть настоящие пропорции комнаты
    # Четыре вида одной комнаты из ОДНОЙ точки: игрок стоит посреди комнаты и
    # поворачивается стрелками. Общая точка — это и есть связность: кадры нельзя
    # собрать по отдельности, иначе окно и шкаф разъедутся между видами.
    # 20 мм: с 1,5 м до стены более длинное стекло видит полстены
    # Строгий поворот из геометрического центра не вышел: до шкафа остаётся метр,
    # и кадр упирается в него вплотную. Поэтому каждый вид снят от своего угла,
    # но кадры ПЕРЕКРЫВАЮТСЯ: шкаф виден и с «двери», и со «стола», кровать —
    # и со своего вида, и из-за плеча. Перекрытие и держит комнату целой
    c["room_desk"] = B.camera("room_desk", (1.7, 4.5, EYE), (1.5, 7.4, 0), 22, shift=SH)
    c["room_closet"] = B.camera("room_closet", (1.25, 4.5, EYE), (3.4, 6.5, 0), 22, shift=SH)
    c["room_bed"] = B.camera("room_bed", (2.55, 6.6, 1.35), (0.25, 5.5, 0.4), 24, shift=-0.08)
    c["room_door"] = B.camera("room_door", (0.62, 6.3, EYE), (2.7, 4.3, 0), 22, shift=SH)
    # Кадр рабочего места крупно: 50 мм, в кадр влезает 1,6 м вместо 4,2 м. Это рычаг
    # детализации — плотность пикселей на предмет задаётся не разрешением фона,
    # а тем, сколько метров помещается в кадр (ai-pipeline.md 5.10)
    c["room_pc"] = B.camera("room_pc", (1.42, 4.55, 1.35), (1.42, 7.4, 0), 50, shift=-0.06)
    c["kitchen"] = B.camera("kitchen", (3.75, 4.6, EYE), (5.7, 6.8, 0), 28, shift=SH)
    c["living"] = B.camera("living", (9.1, 7.05, EYE), (6.4, 4.5, 0), 28, shift=SH)
    c["room_mate"] = B.camera("room_mate", (7.2, 2.85, EYE), (4.3, 0.3, 0), 28, shift=SH)
    c["bath"] = B.camera("bath", (2.25, 2.85, EYE), (0.5, 0.3, 0), 24, shift=SH)
    # Прихожая от входной двери и коридор во всю длину: здесь герой встречает соседку
    c["hall"] = B.camera("hall", (9.2, 0.6, 1.55), (7.6, 3.8, 0), 24, shift=SH)
    c["corridor"] = B.camera("corridor", (7.2, 3.65, 1.55), (0.2, 3.65, 0), 24, shift=SH)
    # Планировка сверху — референс для себя, не кадр игры
    c["plan"] = B.camera("plan", (W / 2, D / 2, 16.0), (W / 2, D / 2, 0.0),
                         ortho=D * 1280 / 720 + 0.6)
    c["iso"] = B.iso_camera("iso", (W / 2, D / 2, 0.8), 13.5)
    return c


def main():
    a = B.args()
    B.reset()
    shell(a.shade)
    partitions(a.shade)
    furniture(a.shade)
    B.light(a.phase, a.shade)
    if a.shade == "lit" and a.phase in ("evening", "night"):
        for name, (x, y, w, d) in ROOMS.items():
            B.lamp(f"lamp_{name}", (x + w / 2, y + d / 2, H - 0.15),
                   energy=120.0 if w * d < 7 else 220.0)
    cams = cameras()
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                        "assets", "_source", "blockout")
    root = os.path.normpath(root)
    total = sum(w * d for _, _, w, d in ROOMS.values())
    print("[blockout] площади, м²: " + ", ".join(
        f"{n} {w * d:.1f}" for n, (_, _, w, d) in ROOMS.items()) + f"; всего {total:.1f}")
    B.finish(cams, a, os.path.join(root, "renders"),
             os.path.join(root, "apartment.blend"),
             hide={"plan": ("_ceil",), "iso": ("_ceil",)})


main()
