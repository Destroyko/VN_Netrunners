# Блокаут съёмной квартиры: источник истины по планировке (docs/art/ai-pipeline.md, 5.7).
#
# По лору герой снимает комнату у домовладельца, в квартире уже живёт соседка
# (docs/story/main-arc.md). Поэтому квартира общая: две жилые комнаты, гостиная,
# кухня, раздельный санузел, прихожая с коридором.
#
# В MVP фоны нужны только комнате героя и кухне (docs/world/locations.md), но строим
# квартиру целиком: смысл блокаута в том, что все кадры — одна и та же квартира.
#
# Запуск (PowerShell):
#   & "C:\Program Files\Blender Foundation\Blender 5.3\blender.exe" -b `
#     --python tools\blockout\apartment.py -- --render all
# Открыть в редакторе: тот же вызов без -b и без --render.

import os
import sys

sys.path.append(os.path.dirname(os.path.abspath(__file__)))
import bl_common as B  # noqa: E402

H = 2.7           # высота потолка
WT = 0.12         # внутренние перегородки
WT_OUT = 0.3      # несущие наружные стены
DOOR = (0.9, 0.0, 2.1)      # (ширина, низ, верх)
WIDE = (1.4, 0.0, 2.1)      # широкий проём без двери
WIN = (0.9, 2.2)            # низ и верх окна

# Планировка: имя -> (x, y, ширина, глубина). Внутренние размеры в метрах,
# начало координат — левый нижний угол квартиры изнутри. Править здесь.
ROOMS = {
    "room_hero":  (0.0, 4.3, 3.4, 3.1),   # комната героя: ПК, сон, инвентарь
    "kitchen":    (3.4, 4.3, 2.6, 3.1),   # кухня: еда
    "living":     (6.0, 4.3, 3.4, 3.1),   # гостиная: общая, диван и ТВ
    "bath":       (0.0, 0.0, 2.4, 3.0),   # ванная
    "wc":         (2.4, 0.0, 1.2, 3.0),   # туалет отдельно
    "room_mate":  (3.6, 0.0, 3.8, 3.0),   # комната соседки
    "hall":       (7.4, 0.0, 2.0, 4.3),   # прихожая: входная дверь
    "corridor":   (0.0, 3.0, 7.4, 1.3),   # коридор
}
W = 9.4           # вся квартира внутри
D = 7.4


def shell(shade):
    """Наружные стены, окна и входная дверь."""
    # низ (Y=0): окно комнаты соседки
    B.wall("ext_s", (0, 0), (W, 0), H, WT_OUT, "wall", shade,
           [(4.8, 1.4, *WIN)])
    # верх (Y=D): окна комнаты героя, кухни и гостиной
    B.wall("ext_n", (0, D), (W, D), H, WT_OUT, "wall", shade,
           [(1.0, 1.4, *WIN), (4.1, 1.2, *WIN), (7.0, 1.6, *WIN)])
    # лево (X=0): форточка в ванной, выше человеческого роста
    B.wall("ext_w", (0, 0), (0, D), H, WT_OUT, "wall", shade,
           [(0.9, 0.6, 1.6, 2.2)])
    # право (X=W): входная дверь в прихожую и окно гостиной
    B.wall("ext_e", (W, 0), (W, D), H, WT_OUT, "wall", shade,
           [(1.2, 1.0, 0.0, 2.1), (5.4, 1.4, *WIN)])


def partitions(shade):
    """Внутренние перегородки. Проёмы задают, что видно из какого кадра."""
    # Y=4.3: жилая полоса / коридор и прихожая
    B.wall("in_n", (0, 4.3), (W, 4.3), H, WT, "wall_in", shade,
           [(2.3, *DOOR),          # комната героя
            (4.3, *DOOR),          # кухня
            (8.0, *WIDE)])         # гостиная открывается из прихожей
    # Y=3.0: коридор / санузел и комната соседки
    B.wall("in_s", (0, 3.0), (7.4, 3.0), H, WT, "wall_in", shade,
           [(0.9, *DOOR),          # ванная
            (2.7, 0.7, 0.0, 2.1),  # туалет, дверь уже
            (5.2, *DOOR)])         # комната соседки
    # вертикальные
    B.wall("in_x34", (3.4, 4.3), (3.4, D), H, WT, "wall_in", shade)
    B.wall("in_x60", (6.0, 4.3), (6.0, D), H, WT, "wall_in", shade)
    B.wall("in_x24", (2.4, 0), (2.4, 3.0), H, WT, "wall_in", shade)
    B.wall("in_x36", (3.6, 0), (3.6, 3.0), H, WT, "wall_in", shade)
    B.wall("in_x74", (7.4, 0), (7.4, 3.0), H, WT, "wall_in", shade)

    for name, (x, y, w, d) in ROOMS.items():
        # Потолок нужен: без него верх интерьерного кадра — дыра в пустоту.
        # Для вида сверху он прячется при рендере.
        B.room_shell(name, (x, y), (w, d), H, True, True, shade)


